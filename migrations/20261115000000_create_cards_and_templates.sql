CREATE TABLE TEMPLATES (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL
) STRICT;

CREATE TABLE CARDS (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    note_id INTEGER NOT NULL UNIQUE REFERENCES NOTES(id) ON DELETE RESTRICT,
    template_id INTEGER NOT NULL REFERENCES TEMPLATES(id) ON DELETE RESTRICT,
    deck_id INTEGER NOT NULL REFERENCES DECKS(id) ON DELETE RESTRICT,
    created_at INTEGER NOT NULL,
    updated_at INTEGER NOT NULL
) STRICT;

CREATE INDEX idx_cards_template_id ON CARDS(template_id);
CREATE INDEX idx_cards_deck_id ON CARDS(deck_id);
